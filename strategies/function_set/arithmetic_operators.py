"""
算术运算符策略模块
包含所有用于GP遗传编程的算术运算函数
使用numpy实现底层运算，但包装为自定义函数以便于管理和扩展
"""

import numpy as np


# ============================================================================
# 基础算术运算符
# ============================================================================

def addition(x, y):
    """加法运算"""
    return np.add(x, y)


def subtraction(x, y):
    """减法运算"""
    return np.subtract(x, y)


def multiplication(x, y):
    """乘法运算"""
    return np.multiply(x, y)


def division(x, y):
    """除法运算（带保护机制）"""
    return np.divide(x, y)


# ============================================================================
# 幂运算函数
# ============================================================================

def square(x):
    """平方运算"""
    return np.square(x)


def cube(x):
    """立方运算"""
    return np.power(x, 3)


def square_root(x):
    """平方根运算"""
    return np.sqrt(x)


def cube_root(x):
    """立方根运算"""
    return np.cbrt(x)


# ============================================================================
# 对数和指数函数
# ============================================================================

def logarithm(x):
    """自然对数运算"""
    return np.log(x)


def log_transform(x):
    """对数变换 - 处理REE数据的对数正态分布"""
    return np.log(x)


def log10_transform(x):
    """以10为底的对数变换"""
    return np.log10(x)


# ============================================================================
# 比较和选择函数
# ============================================================================

def maximum(x, y):
    """最大值选择"""
    return np.maximum(x, y)


def minimum(x, y):
    """最小值选择"""
    return np.minimum(x, y)


def mean(x, y):
    """平均值计算（安全版本）"""
    return (x + y) / 2

